package com.smsgateway.model.enums;

/**
 * 一条投递记录的状态。
 *
 * <p>把 {@code FAILED} 与 {@code DEAD} 分开是有用的：前者是「这次没成功、还会再试」，
 * 后者是「已经放弃，需要人介入」。管理端要能一眼筛出后者 —— 那才是需要人管的那些。
 * 合成一个「失败」，运维就得逐条点开看还会不会重试。
 */
public enum NotifyDeliveryStatus {

    /** 待投递。调度器只捞这个状态且 {@code next_retry_at} 到点的行。 */
    PENDING,

    /**
     * 已取出、正在发送。
     *
     * <p>存在的意义是**卡死识别**：进程在发送途中被杀，这一行会永远停在 SENDING。
     * 调度器定期把停留过久的 SENDING 退回 PENDING（见 NotifyDispatcher），
     * 否则那条短信就静默地再也不发了。
     */
    SENDING,

    SUCCESS,

    /** 本次失败，还会按退避重试。 */
    FAILED,

    /**
     * 渠道被停用，这条不再投递。
     *
     * <p>**为什么不删掉而留个终态**：投递记录是「这条短信本该发到哪」的唯一凭据。
     * 删掉之后，过一阵子没人说得清那条验证码当初到底有没有转发过 —— 而这个问题的
     * 答案在事故复盘里是要用的。留着的代价只是列表里多几行灰字。
     *
     * <p>与 {@link #DEAD} 的区别：DEAD 是「试过了、放弃了，需要人看一眼」；
     * CANCELLED 是「人主动停用了渠道，属于预期内」。混成一个会让「需要处理的那些」
     * 淹没在一堆本就不该发的记录里。
     */
    CANCELLED,

    /** 已用尽重试次数或遇到不可重试的错误，不再尝试。需要人工重投。 */
    DEAD
}
